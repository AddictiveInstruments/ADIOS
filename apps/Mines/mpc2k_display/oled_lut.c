uint8_t oled_lut[256][4];

void oled_lut_init(void)
{
    for (uint32_t v = 0; v < 256; v++)
        for (uint32_t pair = 0; pair < 4; pair++) {
            uint8_t p_left  = (v >> (7 - pair*2)) & 1;   /* pixel MSB de la paire -> nibble bas */
            uint8_t p_right = (v >> (6 - pair*2)) & 1;   /* pixel suivant -> nibble haut */
            oled_lut[v][pair] = (p_right ? 0xF0 : 0x00) | (p_left ? 0x0F : 0x00);
        }
}

