void TFT_SetRotation(u8 r)
{

	TFT_SendCommand(ILI9488_MADCTL);
	u8 rotation = r % 4; // can't be higher than 3
	switch (rotation) {
	case 0:
		TFT_SendData(MADCTL_MX | MADCTL_BGR);
		width = TFT_WIDTH;
		height = TFT_HEIGHT;
		break;
	case 1:
		TFT_SendData(MADCTL_MV | MADCTL_BGR);
		width = TFT_HEIGHT;
		height = TFT_WIDTH;
		break;
	case 2:
		TFT_SendData(MADCTL_MY | MADCTL_BGR);
		width = TFT_WIDTH;
		height = TFT_HEIGHT;
		break;
	case 3:
		TFT_SendData(MADCTL_MX | MADCTL_MY | MADCTL_MV | MADCTL_BGR);
		width = TFT_HEIGHT;
		height = TFT_WIDTH;
		break;
	}

}

