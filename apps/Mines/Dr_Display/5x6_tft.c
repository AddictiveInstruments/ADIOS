void TFT_DrawChar(s16 x, s16 y, unsigned char c, u16 color, u16 bg, u8 size)
{
	if(rotationNum == 1 || rotationNum ==3)
	{
		if((x >= TFT_WIDTH)            || // Clip right
				(y >= TFT_HEIGHT)           || // Clip bottom
				((x + 6 * size - 1) < 0) || // Clip left
				((y + 8 * size - 1) < 0))   // Clip top
			return;
	}
	else
	{
		if((y >= TFT_WIDTH)            || // Clip right
				(x >= TFT_HEIGHT)           || // Clip bottom
				((y + 6 * size - 1) < 0) || // Clip left
				((x + 8 * size - 1) < 0))   // Clip top
			return;
	}


	if(!_cp437 && (c >= 176)) c++; // Handle 'classic' charset behavior

	for (int8_t i=0; i<6; i++ ) {
		u8 line;
		if (i == 5)
			line = 0x0;
		else
			line = pgm_read_byte(font1+(c*5)+i);
		for (int8_t j = 0; j<8; j++) {
			if (line & 0x1) {
				if (size == 1) // default size
					TFT_DrawPixel(x+i, y+j, color);
				else {  // big size
					TFT_FillRect(x+(i*size), y+(j*size), size + x+(i*size), size+1 + y+(j*size), color);
				}
			} else if (bg != color) {
				if (size == 1) // default size
					TFT_DrawPixel(x+i, y+j, bg);
				else {  // big size
					TFT_FillRect(x+i*size, y+j*size, size + x+i*size, size+1 + y+j*size, bg);
				}
			}
			line >>= 1;
		}
	}
}
